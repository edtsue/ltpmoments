/* Ask the deployed Gemini function to define the popular targets, once, and
   write them into data/audiences.js.

   WHY BUILD TIME. Generating these in the browser would mean the rail cannot
   draw until Gemini answers, two people looking at the same board would see
   different numbers, and a dead key would empty the group. Generated here they
   are reviewed like any other data, committed, and hand-editable — which
   matters, because every index in them is an ESTIMATE.

   WHY THE DEPLOYED FUNCTION rather than the Gemini API directly: GEMINI_KEY
   lives in Vercel as an encrypted variable, so it cannot be read back out to
   run locally. The key stays where it is and this script goes through the site.
   The site is gated, so it unlocks first with GATE_PW.

   Run:
     GATE_PW=… node tools/define-audiences.mjs
     GATE_PW=… node tools/define-audiences.mjs --base https://ltpmoments.mfgpilots.com
     node tools/define-audiences.mjs --dry            (prints, writes nothing)

   Only the block between the AUDIENCES markers is rewritten. GROUPS and
   CAT_COLOR above and below it are hand-written and stay untouched.           */

import { readFileSync, writeFileSync } from 'node:fs';

const arg = name => {
  const i = process.argv.indexOf(name);
  return i > -1 ? process.argv[i + 1] : undefined;
};
const BASE = (arg('--base') || 'https://ltpmoments.mfgpilots.com').replace(/\/$/, '');
const DRY = process.argv.includes('--dry');
const GATE_PW = process.env.GATE_PW;

/* The five, and the brief each one is defined from. The brief is the input a
   planner would type into the panel — kept here so the built-in five and a
   user's own custom audience travel the identical path. */
const WANTED = [
  {
    id: 'millennials',
    brief: 'Millennials — adults roughly 30 to 45. The generation that came up with the internet, ' +
           'now with careers and often young children. Streaming-first, nostalgic, still the biggest ' +
           'ticket buyers for live music.'
  },
  {
    id: 'genz',
    brief: 'Gen Z — adults roughly 18 to 27. Social-first discovery, creator-led taste, ' +
           'sets the language everyone else borrows six months later. Sceptical of advertising ' +
           'that announces itself.'
  },
  {
    id: 'genalpha',
    brief: 'Gen Alpha — children and young teenagers, roughly 8 to 15, reached with and through ' +
           'their parents. Gaming and short-form video are the default media; co-viewing is normal; ' +
           'anything bought for them is bought by an adult.'
  },
  {
    id: 'soccermoms',
    brief: 'Soccer moms — mothers roughly 30 to 50 with school-age children at home, suburban, ' +
           'the household decision maker. The year is organised around a school calendar, ' +
           'kids’ sport and family holidays.'
  },
  {
    id: 'earlyadopters',
    brief: 'Early adopters — adults roughly 25 to 44 who buy in the first quarter of a product ' +
           'cycle, follow launches and keynotes, and are asked for advice by everyone else ' +
           'in their circle.'
  }
];

/* ---------- getting in ---------- */

async function unlock() {
  const r = await fetch(`${BASE}/api/gate`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ password: GATE_PW || '', remember: false })
  });
  const j = await r.json().catch(() => ({}));

  /* No GATE_PW set on the deployment at all — middleware fails open, so there
     is nothing to unlock and no cookie to carry. */
  if (r.ok && j.open) return '';
  if (!r.ok) {
    throw new Error(r.status === 401
      ? 'GATE_PW did not match the deployment. Set the same value the site is using.'
      : `gate returned ${r.status}`);
  }
  const raw = r.headers.get('set-cookie') || '';
  const cookie = raw.split(';')[0];
  if (!cookie) throw new Error('the gate accepted the password but set no cookie');
  return cookie;
}

async function define(brief, cookie) {
  const r = await fetch(`${BASE}/api/gemini`, {
    method: 'POST',
    headers: Object.assign({ 'content-type': 'application/json' }, cookie ? { cookie } : {}),
    body: JSON.stringify({ action: 'define-audience', description: brief })
  });
  const j = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error(j.error || `gemini returned ${r.status}`);
  return j;
}

/* ---------- writing it back ---------- */

const BEGIN = '/* AUDIENCES:BEGIN — generated by tools/define-audiences.mjs. */';
const END = '/* AUDIENCES:END */';

const q = s => JSON.stringify(String(s));

function render(records, stamp) {
  const body = records.map(r => {
    const aff = r.pairs.map(p => `      ${q(p.label)}: ${p.value}`).join(',\n');
    const ent = r.entities.length
      ? `\n    ent: {\n${r.entities.map(e => `      ${q(e.label)}: ${e.value}`).join(',\n')}\n    },`
      : '\n    ent: {},';
    const why = r.pairs.filter(p => p.why).map(p => `      ${q(p.label)}: ${q(p.why)}`).join(',\n');
    return `  {
    id: ${q(r.id)},
    group: 'popular',
    /* ESTIMATED. Reasoned from the brief below, not read off a panel. */
    est: true,
    brief: ${q(r.brief)},
    name: ${q(r.name)},
    def: ${q(r.def)},
    /* No size. Size weights a blend, and an invented one would weight it
       wrongly and silently; with none, the blend says so and counts each
       audience equally. */
    size: '',
    aff: {
${aff}
    },${ent}
    why: {
${why}
    }
  }`;
  }).join(',\n');

  return `${BEGIN}
/* ${records.length} audiences, defined ${stamp}.

   EVERY NUMBER HERE IS AN ESTIMATE. There is no panel behind it — each index
   was reasoned from the one-line brief kept on the record, and each carries a
   \`why\` naming the behaviour it rests on. That is why every one of them is
   marked \`est: true\`, which the rail renders as a badge on the audience and
   which must survive anywhere these are shown.

   Hand-edit any of it. A planner who knows better than the estimate is the
   point; re-running this script overwrites the block, so put a real cut in
   through the panel rather than here if you want it to stick. */
export const AUDIENCES = [
${body}
];
${END}`;
}

/* ---------- run ---------- */

const path = new URL('../data/audiences.js', import.meta.url);
const file = readFileSync(path, 'utf8');
if (!file.includes(BEGIN) || !file.includes(END)) {
  console.error('data/audiences.js has no AUDIENCES:BEGIN/END markers to write between.');
  process.exit(1);
}

if (!GATE_PW) {
  console.error('GATE_PW is not set. The site is gated, so the script cannot reach /api/gemini without it.');
  console.error('Run:  GATE_PW=… node tools/define-audiences.mjs');
  process.exit(1);
}

console.log(`base: ${BASE}`);
const cookie = await unlock();
console.log(cookie ? 'unlocked' : 'deployment is open — no gate to pass');

const records = [];
for (const want of WANTED) {
  process.stdout.write(`  ${want.id.padEnd(15)}`);
  try {
    const out = await define(want.brief, cookie);
    records.push(Object.assign({}, out, { id: want.id, brief: want.brief }));
    const spread = out.pairs.map(p => p.value);
    console.log(`${out.name} — ${out.covered}/${out.of} categories, ` +
                `${Math.min(...spread)}–${Math.max(...spread)}, ${out.entities.length} entities`);
    if (out.dropped && out.dropped.length) {
      for (const d of out.dropped) console.log(`      dropped ${d.label} (${d.why})`);
    }
  } catch (e) {
    console.log(`FAILED — ${e.message}`);
    process.exitCode = 1;
  }
}

if (records.length !== WANTED.length) {
  console.error(`\n${records.length} of ${WANTED.length} defined. Nothing written — a partial roster is worse than the old one.`);
  process.exit(1);
}

const stamp = new Date().toISOString().slice(0, 10);
const block = render(records, stamp);

if (DRY) {
  console.log('\n--- would write ---\n');
  console.log(block);
  process.exit(0);
}

const start = file.indexOf(BEGIN);
const finish = file.indexOf(END) + END.length;
writeFileSync(path, file.slice(0, start) + block + file.slice(finish));
console.log(`\nwrote ${records.length} audiences into data/audiences.js`);
